describe('spawn (pickMonsterForFloor)', () => {
  it('only spawns monsters whose location and floorRange match', () => {
    const locs = new Set(monsters.regular.map((m) => m.locationId!))
    for (const locId of [...locs].slice(0, 5)) {
      const loc = locationMap[locId]
      if (!loc || !loc.floors) continue
      const enemy = pickMonsterForFloor(locId, 1, () => 0)
      if (!enemy) continue
      expect(enemy.locationId).toBe(locId)
      const def = monsters.regular.find((m) => m.id === enemy.id)!
      expect(def.locationId).toBe(locId)
      expect(1).toBeGreaterThanOrEqual(def.floorRange![0])
      expect(1).toBeLessThanOrEqual(def.floorRange![1])
    }
  })

  it('raw floor stats = base + scaling × floor (V0 skips the balance pass)', () => {
    const withScaling = monsters.regular.find(
      (m) => m.locationId && m.floorRange && m.scaling && m.floorRange[1] >= 3,
    )!
    const floor = Math.min(3, withScaling.floorRange![1])
    const s = withScaling.scaling!
    expect(statsAtFloor(withScaling, floor)).toEqual({
      hp: Math.round(withScaling.baseStats.hp + s.hpPerFloor * floor),
      def: Math.round(withScaling.baseStats.def + s.defPerFloor * floor),
      atk: Math.round(withScaling.baseStats.atk + s.atkPerFloor * floor),
    })

    // And a spawned enemy's stats come from ITS OWN def via the same formula.
    const enemy = pickMonsterForFloor(withScaling.locationId!, floor, () => 0.99)!
    const spawnedDef = monsters.regular.find((m) => m.id === enemy.id)!
    const ss = spawnedDef.scaling ?? { hpPerFloor: 0, defPerFloor: 0, atkPerFloor: 0 }
    expect(enemy.maxHp).toBe(Math.round(spawnedDef.baseStats.hp + ss.hpPerFloor * floor))
    expect(enemy.atk).toBe(Math.round(spawnedDef.baseStats.atk + ss.atkPerFloor * floor))
    expect(enemy.def).toBe(Math.round(spawnedDef.baseStats.def + ss.defPerFloor * floor))
  })

  it('rewards come from regulateMonsterXp, never monsters.json rewards', () => {
    const locId = 'newbie_hollow'
    const enemy = pickMonsterForFloor(locId, 1, () => 0.99)!
    const regulated = regulateMonsterXp(locId, 1, false)
    expect(enemy.xp).toBe(regulated.xp)
    expect(enemy.solars).toBe(regulated.solars)
  })

  it('elite roll: rng below the depth chance picks an elite when the pool has one', () => {
    const locWithElites = monsters.regular.find(
      (m) => m.tier === 'elite' && m.locationId && m.floorRange,
    )!
    const locId = locWithElites.locationId!
    const floor = locWithElites.floorRange![0]
    // rng 0 → always under the elite chance → elite chosen (pool has elites)
    const eliteEnemy = pickMonsterForFloor(locId, floor, () => 0)
    const anyEnemy = pickMonsterForFloor(locId, floor, () => 0.999)
    expect(eliteEnemy).not.toBeNull()
    expect(anyEnemy).not.toBeNull()
    if (monsters.regular.some((m) => m.locationId === locId && m.tier === 'regular' && m.floorRange && floor >= m.floorRange[0] && floor <= m.floorRange[1])) {
      expect(eliteEnemy!.tier).toBe('elite')
      expect(anyEnemy!.tier).toBe('regular')
    }
  })

  it('depthRatio runs 0 → 1 across a dungeon', () => {
    expect(depthRatio('newbie_hollow', 1)).toBe(0)
    expect(depthRatio('newbie_hollow', 50)).toBe(1)
    expect(depthRatio('newbie_hollow', 25)).toBeCloseTo(24 / 49, 10)
  })

  it('startBattle throws when a floor has no monster pool', () => {
    expect(() => startBattle('astral_town', 1)).toThrow('No monsters')
  })

  it('boss floors spawn their authored boss with regulated milestone rewards', () => {
    expect(bossForFloor('newbie_hollow', 50)?.id).toBe('nh_hollow_gatekeeper')
    expect(nextBossFloor('newbie_hollow', 1)).toBe(50)
    expect(nextBossFloor('gambits_dungeon', 21)).toBe(30)

    const nh50 = startBattle('newbie_hollow', 50)
    expect(nh50.enemy.isBoss).toBe(true)
    expect(nh50.enemy.tier).toBe('boss')
    expect(nh50.enemy.id).toBe('nh_hollow_gatekeeper')
    expect(nh50.enemy.conquestTitle).toBe('Hollow Graduate')
    expect(nh50.enemy.xp).toBe(554)
    expect(nh50.enemy.solars).toBe(194)

    // season_01_ruins F100 has NO regular pool — only The Last Prayer boss
    const s1 = startBattle('season_01_ruins', 100)
    expect(s1.enemy.id).toBe('the_last_prayer')
    expect(s1.enemy.isBoss).toBe(true)

    const stm = spawnBossForFloor('stormpeak', 100)!
    expect(stm.id).toBe('boss_storm_100')
    expect(stm.conquestTitle).toBe('Stormbreaker')
  })
})

// ── Turn flow ──────────────────────────────────────────────────────────────

const NOW = new Date('2026-11-25T12:00:00').getTime()

function makeFight(
  opts: { player?: Player; floor?: number; enemy?: Partial<Enemy> } = {},
): { player: Player; session: BattleSession } {
  const player = opts.player ?? createNewPlayer({ name: 'Astra', classId: 'warrior', raceId: 'human' }, NOW)
  const session = startBattle('newbie_hollow', opts.floor ?? 1, () => 0.999)
  Object.assign(session.enemy, opts.enemy ?? {})
  return { player, session }
}

describe('turn flow', () => {
  it('a basic attack lands and cuts enemy hp by the mitigated amount', () => {
    const { player, session } = makeFight()
    const before = session.enemy.hp
    // rng sequence: hit roll (0 → hit), crit roll (1 → no crit), enemy hit roll (1 → enemy misses)
    const rng = seq(0, 1, 1)
    const r = playerAction(player, session, { kind: 'attack' }, rng)
    expect(r.status).toBe('active')
    const hit = r.events.find((e) => e.kind === 'hit')
    expect(hit).toBeTruthy()
    // warrior lv1: primary str 10, mult 1 → raw 10 → applyDefense(10, enemyDef)
    const expectedDmg = applyDefense(calcPlayerDamage(player, null, 1, 0, () => 1).rawDmg, session.enemy.def)
    expect(before - session.enemy.hp).toBe(expectedDmg)
    expect(session.turn).toBe(2)
  })

  it('a miss deals nothing but the enemy still counters', () => {
    const { player, session } = makeFight()
    const hpBefore = session.enemy.hp
    const playerHpBefore = player.hp
    // rng: hit roll 1 (miss), enemy hit roll 0 (hit), enemy damage variance 0.5
    const rng = seq(1, 0, 0.5)
    const r = playerAction(player, session, { kind: 'attack' }, rng)
    expect(r.events.some((e) => e.kind === 'miss')).toBe(true)
    expect(session.enemy.hp).toBe(hpBefore)
    expect(player.hp).toBeLessThan(playerHpBefore)
  })

  it('skills cost MP and refuse when the pool is short', () => {
    const { player, session } = makeFight()
    const skillId = player.equippedSkills.find((id) => skillMap[id]!.mpCost > 0)
    expect(skillId).toBeTruthy()
    const cost = skillMap[skillId!]!.mpCost

    // starve the pool
    player.mp = cost - 1
    const blocked = playerAction(player, session, { kind: 'skill', skillId: skillId! }, () => 1)
    expect(blocked.events.some((e) => e.kind === 'error')).toBe(true)
    expect(player.mp).toBe(cost - 1) // nothing spent

    // afford it
    player.mp = cost
    const ok = playerAction(player, session, { kind: 'skill', skillId: skillId! }, seq(0, 1, 1))
    expect(player.mp).toBe(0)
    expect(ok.events.some((e) => e.kind === 'info' && e.text.includes('uses'))).toBe(true)
  })

  it('cannot use a skill the player does not own/equip', () => {
    const { player, session } = makeFight()
    const r = playerAction(player, session, { kind: 'skill', skillId: 'mage_fireball' }, () => 1)
    expect(r.events.some((e) => e.kind === 'error')).toBe(true)
  })

  it('type matchup multiplies AFTER defense, with its own floor of 1', () => {
    const { player, session } = makeFight()
    // Make the enemy explicitly weak to the warrior's physical skill
    session.enemy.weakTo = ['physical']
    session.enemy.type = 'physical'
    const skillId = player.equippedSkills.find((id) => skillMap[id]?.effects?.[0]?.type === 'attack' && skillMap[id]?.element === 'physical')
      ?? player.equippedSkills.find((id) => skillMap[id]?.effects?.[0]?.type === 'attack')!
    const skill = skillMap[skillId]!
    const before = session.enemy.hp

    playerAction(player, session, { kind: 'skill', skillId }, seq(0, 1, 1))

    const base = applyDefense(calcPlayerDamage(player, skill, 1, 0, () => 1).rawDmg, session.enemy.def)
    // matchup: physical category vs physical type = 1 base; weakTo physical → ×1.34
    const expected = Math.max(1, Math.floor(base * 1.34))
    expect(before - session.enemy.hp).toBe(expected)
  })

  it('defend regenerates 5% max MP and halves the incoming strike via double DEF', () => {
    // DEF matters against the +500 pivot only at high values — use 150 so the
    // doubled-DEF effect is visible (bot's design: defending is for bosses).
    const { player, session } = makeFight()
    player.stats.def = 150
    player.mp = 0 // observe the regen (a full bar would clamp)
    const regen = Math.floor(player.maxMp * 0.05)

    // Defend: rng for enemy hit roll (0 → hit) then variance 0.5
    const r = playerAction(player, session, { kind: 'defend' }, seq(0, 0.5))
    expect(r.events.some((e) => e.text.includes('defends'))).toBe(true)
    expect(player.mp).toBe(regen)
    expect(session.defending).toBe(false) // consumed by the counter

    const hpLostDefending = player.maxHp - player.hp
    expect(hpLostDefending).toBeGreaterThan(0)

    // fresh fight with the same DEF, no defend, identical rng → strictly more damage
    const f2 = makeFight()
    f2.player.stats.def = 150
    playerAction(f2.player, f2.session, { kind: 'attack' }, seq(0, 1, 0, 0.5)) // player hits, enemy hits
    const hpLostAttacking = f2.player.maxHp - f2.player.hp
    expect(hpLostDefending).toBeLessThan(hpLostAttacking)
  })

  it('winning settles rewards: xp, solars, wins++, level-ups when xp crosses a threshold', () => {
    const { player, session } = makeFight({ enemy: { hp: 1, def: 0 } })
    player.xp = 340 // 348 reaches level 2
    const r = playerAction(player, session, { kind: 'attack' }, seq(0, 1, 1))
    expect(r.status).toBe('won')
    expect(session.status).toBe('won')
    expect(r.rewards).toBeTruthy()
    expect(r.rewards!.xp).toBeGreaterThan(0)
    // Tutorial hooks fire on the first win: claim_character (+100, stateCheck)
    // and fight_monster (+125, trigger) — solars only, never XP.
    expect(player.wallet.solars).toBe(100 + 100 + 125 + r.rewards!.solars)
    expect(player.stats.wins).toBe(1)
    expect(player.xp).toBe(340 + r.rewards!.xp)
    // survival xp at (1,1) = 87 → 427 ≥ 348 → level 2
    expect(player.level).toBe(2)
    expect(r.events.some((e) => e.kind === 'win')).toBe(true)
    expect(r.events.some((e) => e.kind === 'levelup')).toBe(true)
  })

  it('winning stops the enemy from swinging back', () => {
    const { player, session } = makeFight({ enemy: { hp: 1, def: 0 } })
    const hpBefore = player.hp
    playerAction(player, session, { kind: 'attack' }, seq(0, 1, 1))
    expect(player.hp).toBe(hpBefore) // no counter damage
  })

  it('losing records the loss, halves HP/MP and respawns at the hub', () => {
    const { player, session } = makeFight({ enemy: { atk: 100000, def: 999999 } })
    player.inDungeon = true
    player.location = 'newbie_hollow'
    player.hp = 50
    player.mp = 20
    // player misses (1), enemy hits (0), variance 0.5
    const r = playerAction(player, session, { kind: 'attack' }, seq(1, 0, 0.5))
    expect(r.status).toBe('lost')
    expect(player.hp).toBe(Math.floor(player.maxHp * 0.5))
    expect(player.mp).toBe(Math.floor(player.maxMp * 0.5))
    expect(player.stats.losses).toBe(1)
    expect(player.location).toBe('astral_town')
    expect(player.inDungeon).toBe(false)
    expect(r.events.some((e) => e.kind === 'lose')).toBe(true)
  })

  it('no actions after the battle ends', () => {
    const { player, session } = makeFight({ enemy: { hp: 1, def: 0 } })
    playerAction(player, session, { kind: 'attack' }, seq(0, 1, 1))
    const r = playerAction(player, session, { kind: 'attack' }, () => 0)
    expect(r.events.some((e) => e.kind === 'error')).toBe(true)
    expect(session.turn).toBe(1) // never advanced
  })

  it('a full fight under a seeded rng is replayable', () => {
    const run = () => {
      const { player, session } = makeFight({ enemy: { hp: 60, atk: 5, def: 2 } })
      const rng = mulberry32(7)
      let guard = 0
      while (session.status === 'active' && guard++ < 100) {
        playerAction(player, session, { kind: 'attack' }, rng)
      }
      return { player, session }
    }
    const a = run()
    const b = run()
    expect(a.session.status).toBe(b.session.status)
    expect(a.player.hp).toBe(b.player.hp)
    expect(a.player.xp).toBe(b.player.xp)
    expect(a.session.turn).toBe(b.session.turn)
  })
})

